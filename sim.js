const 편향판정 = [];
for (const [라벨, Q] of [['진단서①(4년)', 16], ['진단서③(12년)', 48]]) {
  L('  ── ' + 라벨 + ' ' + '─'.repeat(52));
  L('    일치 = 의도한 성향과 맞은 비율   ·   (  ) = 그 축에서 제일 많이 나온 글자와 그 비중');
  L('    ' + pad('모델', 14) + num('완전일치', 9)
      + num('E/I', 12) + num('S/N', 12) + num('T/F', 12) + num('J/P', 12));
  for (const m of 편향모델) {
    const r = 적중률(Q, undefined, m.편향);
    const 일치 = {};
    for (const k of ['ei','sn','tf','jp']) 일치[k] = r.축일치[k] / r.총판 * 100;
    /* 쏠림 = 그 축에서 제일 많이 나온 글자의 비중.
       16유형을 골고루 플레이시켰는데 한 글자가 압도하면,
       그 축은 성격이 아니라 편향이 정하고 있다는 뜻이다 */
    const 쏠림 = {}, 쏠린글자 = {};
    for (const k of ['ei','sn','tf','jp']) {
      const g = Object.entries(r.글자분포[k]).sort((a,b) => b[1] - a[1])[0];
      쏠린글자[k] = g[0]; 쏠림[k] = g[1] / r.총판 * 100;
    }
    L('    ' + pad(m.이름, 14)
        + num((r.완전일치/r.총판*100).toFixed(0) + '%', 9)
        + ['ei','sn','tf','jp'].map(k =>
            num(일치[k].toFixed(0) + '% (' + 쏠린글자[k] + 쏠림[k].toFixed(0) + ')', 12)).join(''));
    if (m.편향) 편향판정.push({ 모델: m.이름, 때: 라벨, 일치, 쏠림, 쏠린글자 });
  }
  L('');
}

L('  ── 판정 ' + '─'.repeat(58));
let 편향통과 = 0, 편향전체 = 0;
for (const b of 편향판정) {
  for (const [k, nm] of [['ei','E/I'],['sn','S/N'],['tf','T/F'],['jp','J/P']]) {
    편향전체++;
    if (b.쏠림[k] <= 75) { 편향통과++; continue; }
    L('    ✗ ' + pad(b.모델 + ' / ' + b.때, 28) + nm + ' 가 ' + b.쏠린글자[k]
        + ' 로 쏠림 ' + b.쏠림[k].toFixed(0) + '%  (75% 이하)   일치 '
        + b.일치[k].toFixed(0) + '%');
  }
}
L(`\n    ${편향통과}/${편향전체} 통과`);
if (편향통과 < 편향전체)
  L('    ※ 실패는 예상된 것이다 — 이어하기 §1 (배치판 측정 제거) 이 아직 미구현이다.\n'
  + '      이 숫자가 고치기 전/후를 비교하는 기준선이다 (함정 14)');
L('='.repeat(74));
