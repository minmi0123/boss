/* 배치판을 화면의 매출 수치만 보고 고른다 (이어하기 §1-3 의 코드) */
function 수치로고르기(G, S) {
  let best = null, bv = -Infinity;
  for (const k of ['영업', '마케팅', '개발', '외주']) {
    if (!G.선택가능(S, k).가능) continue;
    const v = G.매출(S, k);
    if (v > bv) { bv = v; best = k; }
  }
  // 경고문을 보고 관리하는 수준의 상식은 넣는다 (안 넣으면 모델의 무능을 재게 된다)
  if (S.평판 < 20)        best = G.선택가능(S, '영업').가능 ? '영업' : (best || '개발');
  else if (S.평판 >= 90)  best = G.선택가능(S, '외주').가능 ? '외주' : best;
  return best || '개발';
}

